/// Drop `/* ... */` from a stylesheet before it is inlined into the document.
///
/// The comments in this project's CSS are load-bearing FOR THE SOURCE: they
/// carry the measurements and the reasoning behind almost every value. They
/// are worth nothing to the engine, which discards them during parse, and
/// they are 70% of the 410 KB inlined into every webview: 409,530 bytes
/// becomes 122,894.
///
/// Measured over twenty windows: 37.03 MB per WebProcess with them against
/// 35.64 MB without, so 1.4 MB per window and 37.3 MB across the set.
///
/// Safe here because no stylesheet in this tree puts `/*` inside a string;
/// `no_css_string_hides_a_comment_delimiter` keeps it that way, because a
/// naive stripper would eat the rest of the file from such a string onward.
pub(crate) fn strip_css(css: &str) -> String {
    let mut out = String::with_capacity(css.len() / 3);
    let mut rest = css;
    while let Some(open) = rest.find("/*") {
        out.push_str(&rest[..open]);
        match rest[open + 2..].find("*/") {
            Some(close) => rest = &rest[open + 2 + close + 2..],
            // Unterminated. Keep what came before and stop, rather than
            // shipping the remainder of a file whose structure is unknown.
            None => return out,
        }
    }
    out.push_str(rest);
    out
}

/// How long a start may take before the loading screen appears.
///
/// The screen exists for a cold start: a daemon that has to be launched, a
/// profile that has to be read off a cold disk, a webview process that has to
/// be spawned. It does not exist for a warm one, and showing it there would be
/// a flash of a logo that is gone before it can be read, which is the visual
/// signature of a program that is not sure what it is doing.
///
/// 400 milliseconds is the boundary between "instant" and "waiting" in the
/// interaction literature this product's motion rules already follow, and it
/// is comfortably longer than a warm start on the machines this was measured
/// on. Nothing is inserted into the document before it elapses, so a 200
/// millisecond start renders no overlay at all: not hidden, not zero-opacity,
/// absent.
///
/// # Why the timer around it is JavaScript
///
/// `loading.js` is 2,864 bytes and it does two things: it waits this long,
/// and it takes the overlay down when the first tree is committed. Both look
/// like Rust's work, and neither is, in this shell.
///
/// A Dioxus element cannot be the splash. The splash exists to cover the
/// interval BEFORE the app's root has rendered anything, so an overlay the
/// root renders would first appear at exactly the moment it is meant to be
/// dismissed.
///
/// Rust can reach a live document only by evaluating a script in it. The
/// vendored `dioxus-desktop` exposes the document through `custom_head` /
/// `custom_index`, which are the initial bytes and are already used here, and
/// otherwise through eval; wry offers `evaluate_script` and nothing else that
/// mutates a DOM. So a "Rust" version of this file is the same DOM calls in a
/// `format!`, fired from a Rust one-shot: the same JavaScript, minus the
/// review and minus `chrome::loading_tests`, which runs the real source
/// against a fake clock and is the only proof that a fast start creates no
/// element at all. That trade makes the product worse and the byte count
/// only look better.
///
/// Nor can the delay move into CSS. Revealing a pre-rendered node after
/// `animation-delay` needs a node in the document from the first byte and
/// needs an animation, and both are already refused, by
/// `the_head_pre_renders_no_overlay` and `the_loading_screen_does_not_animate`
/// respectively. A hidden node can be revealed a frame late by a stylesheet
/// that arrives late, which is the flash this whole feature is against, and
/// an animation is a wakeup per frame on the one surface that exists because
/// the process has not started doing work yet.
///
/// What would actually retire the file is the pane going native: a window
/// whose first surface is drawn by Rust has no document to hold back. Until
/// then this stays, and it stays as a reviewed file rather than a string.
pub(crate) const LOADING_SCREEN_DELAY_MS: u64 = 400;

/// The mark, from the one file its geometry is written in.
///
/// Inlined rather than fetched. The loading screen is on screen precisely when
/// nothing else has loaded yet, so a request for the mark is a request that
/// resolves after the thing it was drawn for is over.
///
/// A loading screen is one of the two places the mark is allowed to appear;
/// see `update/where_the_mark_may_appear.rs` for the other and for everywhere
/// it may not.
const BRAND_MARK_SVG: &str = include_str!("../../assets/logo/vitrum.svg");

/// The loading screen's own script, evaluated in the document head.
const LOADING_JS: &str = include_str!("loading.js");

/// The boot splash's own declarations, without the element around them.
///
/// Not a member of [`stylesheets`]: that array is the set of sheets the
/// design-system guards read, and this is not a design-system part. It is
/// three declarations that have to be in force before the first of those
/// sheets is even parsed.
fn loading_css() -> String {
    // The same base the webview is created with, so the screen is the window
    // rather than a panel drawn on top of it. A translucent profile gets a
    // transparent one for the same reason `window_config` does: the operator
    // asked to see through the window, and that includes while it starts.
    let background = if *TRANSLUCENT { "transparent" } else { "#060608" };
    format!(
        "#vitrum-boot{{position:fixed;inset:0;display:flex;\
         align-items:center;justify-content:center;background:{background};\
         color:#4C6EF5;z-index:2147483647}}\
         #vitrum-boot svg{{width:96px;height:96px}}"
    )
}

/// The boot splash's mark and timer.
fn loading_scripts() -> String {
    format!(
        "<script>window.__vitrum_bootDelayMs={LOADING_SCREEN_DELAY_MS};\
         window.__vitrum_bootMark={mark:?};</script>\
         <script>{LOADING_JS}</script>",
        mark = BRAND_MARK_SVG
    )
}

/// Every `<style>` the document head ships, named, in emission order.
///
/// The head is BUILT from this list rather than from a literal run of tags,
/// so a sheet cannot reach the operator without a name here, and the coverage
/// guard has something to enumerate. It used to be a run of literals checked
/// against the number two, and adding the boot splash turned a decision into
/// a surprise failure that read as an off-by-one.
pub(crate) fn style_origins() -> Vec<(&'static str, String)> {
    // One pass over every stylesheet, once per call. The engine gets the
    // declarations; the reasoning stays in the source files where it is read.
    //
    // ONE `<style>`, not sixteen. Cascade order is concatenation order, so
    // joining them changes nothing about which rule wins. What it changes is
    // how many stylesheet objects the engine carries: sixteen per document,
    // and a document per window, so twenty windows in one web process held
    // 320 of them where 20 will do. None of these sheets opens with
    // `@charset` or `@import`, which are the two at-rules that must come
    // first in a sheet and are the only reason not to do this.
    //
    // `stylesheets()` still returns them separately, because the guards that
    // check a class is styled need to name the file that styles it.
    let sheets = stylesheets();
    let mut bundle =
        String::with_capacity(sheets.iter().map(|(_, s)| s.len()).sum::<usize>() + 32);
    for (_, sheet) in sheets.iter() {
        bundle.push_str(&strip_css(sheet));
        bundle.push('\n');
    }
    vec![
        ("vendored xterm.css", XTERM_CSS.to_string()),
        ("the design-system bundle", bundle),
        ("the boot splash", loading_css()),
    ]
}

/// The inlined stylesheet and script bundle, built once for the process.
///
/// `OnceLock` rather than `LazyLock` because the renderer name in it comes off
/// the command line, which does not exist at declaration time. Building it per
/// window would copy the vendored sources for every window that opens, and the
/// string is immutable for the life of the process.
pub(crate) fn document_head(opts: Options) -> &'static str {
    static HEAD: OnceLock<String> = OnceLock::new();
    HEAD.get_or_init(|| {
        boot::mark("head.start");
        // Every sheet, in one place: `style_origins` decides what ships and
        // in what order, and this loop only wraps each one in its element.
        let styles: String = {
            let origins = style_origins();
            let mut out = String::with_capacity(
                origins.iter().map(|(_, css)| css.len() + 16).sum::<usize>(),
            );
            for (_, css) in origins.iter() {
                out.push_str("<style>");
                out.push_str(css);
                out.push_str("</style>");
            }
            out
        };
        boot::mark("head.css");
        // The table the OPERATOR has, not the compile-time default: their
        // rebindings folded in and their saved presets appended. The head is
        // the only copy that is guaranteed to be in place before the first
        // keydown, so shipping defaults here means every rebound chord and
        // every preset shortcut is dead until the mount-time push lands, and
        // silently dead forever if it does not.
        //
        // Hoisted out of the `format!` below so the trace can tell the two
        // costs apart: this reads two files off the profile, and the format
        // copies 800 KB of vendored script.
        let keymap = ui::settings::keymap_json(&ui::settings::live_chords(
            &state::startup_prefs().0.settings.keyboard,
            &launch::load_launch_store().presets,
        ));
        boot::mark("head.keymap");
        let head = format!(
            "{styles}\
             <script>window.__vitrum_renderer={:?};window.__vitrum_keymap={};</script>\
             <script type=\"text/plain\" id=\"rg-vendor-xterm\">{XTERM_JS}</script>\
             <script type=\"text/plain\" id=\"rg-vendor-webgl\">{ADDON_WEBGL_JS}</script>\
             <script type=\"text/plain\" id=\"rg-vendor-fit\">{ADDON_FIT_JS}</script>\
             {loading}",
            opts.renderer.as_str(),
            keymap,
            // `type="text/plain"` so the engine STORES these and does not
            // parse them. `bootstrap.js::loadVendor` evaluates them on the
            // first command that needs a terminal, then clears the element's
            // text so the source is released too.
            //
            // Measured, twenty windows: 41.28 MB per WebProcess with these
            // parsed at startup against 36.30 MB with them absent entirely,
            // so 5.0 MB per window, 105.5 MB across the set. That is the cost
            // of COMPILING 390 KB of JavaScript in every window, and most
            // windows in a twenty-window session never focus a session at all.
            //
            // The WebGL addon is a further 100 KB and always ships, because
            // the Terminal settings row offers WebGL and used to be unable to
            // deliver it: the script was emitted only for `--renderer webgl`,
            // so an operator who picked WebGL in the row got an error flash
            // and a silent revert to DOM, on that launch and on every launch
            // after it, with nothing anywhere mentioning a flag.
            //
            // Shipping it costs 100 KB of DOM text per window and nothing
            // else. It is NOT in `loadVendor`'s list, so the 100 KB is never
            // COMPILED unless the operator actually selects WebGL, which is
            // where the 5.0 MB per window above was spent. Text is cheap;
            // parsing is not.
            // The tag is written into the literal above rather than built as
            // an argument, so the 100 KB is copied once instead of twice.
            loading = loading_scripts(),
        );
        boot::mark("head.done");
        head
    })
    .as_str()
}

/// One window's worth of webview configuration.
pub(crate) fn window_config(
    opts: Options,
    state: &WindowGeometry,
    scale: f64,
    os_scale: f64,
) -> Config {
    let config = Config::new()
        .with_window(window_builder(state, scale, os_scale))
        .with_custom_head(document_head(opts).to_string())
        // A terminal shell has no use for a File/Edit/View menu, and on Linux
        // the default bar steals vertical space from the grid.
        .with_menu(None)
        .with_close_behaviour(WindowCloseBehaviour::WindowCloses)
        // The webview's own base layer. Opaque by default, and fully clear
        // when the profile asked for translucency: WebKit paints this behind
        // the document, so leaving it at 255 would make every `rgba` surface
        // in the stylesheet blend against a solid colour and change nothing.
        .with_background_color(if *TRANSLUCENT {
            (0, 0, 0, 0)
        } else {
            (6, 6, 8, 255)
        });

    // The scheme is registered exactly once for the process, not once per
    // window, and the second window is the one that proves it: every webview
    // is built from one leaked `WebContext` (`vendor/src/webview.rs`,
    // `shared_web_context`), a custom scheme belongs to the context rather
    // than the webview, and registering the same name twice against it is a
    // hard `DuplicateCustomProtocol` error. Attaching this to every config
    // panicked the moment a second window opened. The vendored fork already
    // guards its own `dioxus` scheme this way.
    //
    // Registering once is not a workaround: `backdrop_protocol` is a free
    // function that resolves the path out of the URL, so it holds nothing
    // window-specific, and the context outlives every window it serves.
    if BACKDROP_SCHEME_REGISTERED.swap(true, std::sync::atomic::Ordering::SeqCst) {
        return config;
    }
    config.with_custom_protocol("vitrum-backdrop".to_string(), backdrop_protocol)
}

/// Whether this process has already registered the `vitrum-backdrop` scheme.
static BACKDROP_SCHEME_REGISTERED: std::sync::atomic::AtomicBool =
    std::sync::atomic::AtomicBool::new(false);

/// Serve the operator's backdrop image to the document.
///
/// The page is served from a custom scheme, and a custom scheme cannot fetch
/// `file://`: WebKit treats it as cross-origin and refuses. So the image comes
/// back through a scheme of ours, with the path percent-encoded into the URL
/// by [`ui::settings::backdrop_url`].
///
/// This reads whatever path the profile names, which is the operator's own
/// file on their own machine, chosen through their own file picker. It is
/// deliberately not restricted to a directory: a wallpaper lives wherever the
/// operator keeps wallpapers. What it does refuse is anything that is not an
/// image, because a stylesheet that can name a path is a stylesheet that can
/// ask for `/etc/shadow`, and answering that with bytes would turn a cosmetic
/// setting into a file-read primitive for anyone who can write `ui.json`.
fn backdrop_protocol(
    _id: vitrum_dioxus_desktop::wry::WebViewId,
    request: vitrum_dioxus_desktop::wry::http::Request<Vec<u8>>,
) -> vitrum_dioxus_desktop::wry::http::Response<std::borrow::Cow<'static, [u8]>> {
    use vitrum_dioxus_desktop::wry::http::Response;

    let deny = |code: u16| {
        Response::builder()
            .status(code)
            .body(std::borrow::Cow::Borrowed(&[][..]))
            .expect("a status-only response is always well formed")
    };

    let Some(path) = backdrop_path(request.uri().path()) else {
        return deny(400);
    };
    let Ok(bytes) = std::fs::read(&path) else {
        return deny(404);
    };
    let Some(mime) = image_mime(&bytes) else {
        return deny(415);
    };
    Response::builder()
        .header("Content-Type", mime)
        .body(std::borrow::Cow::Owned(bytes))
        .expect("a response with one header is always well formed")
}

/// The filesystem path out of a `vitrum-backdrop://` URL path.
///
/// Returns `None` for anything that is not an absolute path, which is what a
/// traversal attempt and a malformed URL both look like from here.
pub(crate) fn backdrop_path(uri_path: &str) -> Option<std::path::PathBuf> {
    let decoded = percent_decode(uri_path)?;

    // Every URL path carries a leading slash. On Unix that slash is the root
    // and has to stay. On Windows the path under it is `C:\...`, and the slash
    // makes it rooted-but-driveless, which `is_absolute` rejects: leaving it on
    // would refuse every backdrop on Windows and look like the feature simply
    // does not work there.
    #[cfg(windows)]
    let decoded = decoded.strip_prefix('/').unwrap_or(&decoded).to_string();

    let path = std::path::PathBuf::from(&decoded);
    if !path.is_absolute() {
        return None;
    }

    // Components rather than a split on '/': on Windows a traversal is spelled
    // `..\`, which a slash-split never sees. `..` cannot widen what this serves,
    // because the answer is gated on the bytes being an image either way, but a
    // path that needs normalising is a path nobody chose from a picker.
    if path
        .components()
        .any(|c| c == std::path::Component::ParentDir)
    {
        return None;
    }
    Some(path)
}

/// Percent-decode a URL path into a string, or `None` if it is malformed.
fn percent_decode(s: &str) -> Option<String> {
    let raw = s.as_bytes();
    let mut out = Vec::with_capacity(raw.len());
    let mut i = 0;
    while i < raw.len() {
        if raw[i] == b'%' {
            let hex = raw.get(i + 1..i + 3)?;
            let text = std::str::from_utf8(hex).ok()?;
            out.push(u8::from_str_radix(text, 16).ok()?);
            i += 3;
        } else {
            out.push(raw[i]);
            i += 1;
        }
    }
    String::from_utf8(out).ok()
}

/// The MIME type for `bytes`, by signature, or `None` if it is not an image.
///
/// By content and never by file extension. The extension is attacker-supplied
/// in exactly the case this guards, and the point is to answer only with
/// things that really are images.
pub(crate) fn image_mime(bytes: &[u8]) -> Option<&'static str> {
    const PNG: &[u8] = b"\x89PNG\r\n\x1a\n";
    const GIF87: &[u8] = b"GIF87a";
    const GIF89: &[u8] = b"GIF89a";
    if bytes.starts_with(PNG) {
        return Some("image/png");
    }
    if bytes.starts_with(&[0xFF, 0xD8, 0xFF]) {
        return Some("image/jpeg");
    }
    if bytes.starts_with(GIF87) || bytes.starts_with(GIF89) {
        return Some("image/gif");
    }
    if bytes.len() >= 12 && bytes.starts_with(b"RIFF") && &bytes[8..12] == b"WEBP" {
        return Some("image/webp");
    }
    // SVG is text and has no signature. Refused rather than sniffed: it is a
    // document with scripting and external references, and this one is
    // rendered inside the privileged application page.
    None
}

/// Open another window in this process.
///
/// Windows are independent views, not mirrors: each gets its own [`UiState`],
/// its own tab strip and its own socket to the daemon, which broadcasts every
/// session change to all of them. What is *not* duplicated is the process, and
/// that is the whole point. A second process is a second WebKit engine, a
/// second network process and a second copy of every mapped page; a second
/// window shares all of it.
pub(crate) fn open_window(from: &DesktopContext, opts: Options, link: Option<DeepLink>) {
    let monitors: Vec<MonitorHandle> = from.available_monitors().collect();
    let rects = monitor_rects(from.primary_monitor().as_ref(), &monitors);
    let ordinal = claim_ordinal();

    // A new window opens on the monitor the window that spawned it is on,
    // which is where the user is looking.
    let host = from.current_monitor().or_else(|| from.primary_monitor());
    let density = host.as_ref().map(density_of);
    let scale = opts
        .ui_scale
        .unwrap_or_else(|| density.map_or(MIN_UI_SCALE, Density::ui_scale));
    let os_scale = density.map_or(1.0, |d| d.os_scale).max(1.0);

    let state = remembered(ordinal)
        .map(|s| window_state::clamp_to_monitors(&s, &rects))
        .unwrap_or_else(|| fresh_geometry(host.as_ref(), scale, ordinal));
    remember(ordinal, state);

    let dom = VirtualDom::new(App)
        .with_root_context(opts)
        .with_root_context(WindowSeed { ordinal, link });

    tracing::info!(
        "opening window {ordinal} at {}x{}+{}+{} scale {scale}; {} now open",
        state.width,
        state.height,
        state.x,
        state.y,
        live_window_count()
    );

    // The returned handle resolves once the window exists. Nothing here needs
    // to drive the new window, so it is dropped: the request is already queued
    // on the shared context and the event loop will build it.
    drop(from.new_window(dom, window_config(opts, &state, scale, os_scale)));
}

